        function switchService(clickedBtn, id) {
            document.querySelectorAll('.srv-btn').forEach(function(btn) {
                btn.classList.remove('srv-active');
                btn.classList.add('srv-inactive');
                btn.setAttribute('aria-selected', 'false');
            });

            document.querySelectorAll('.srv-panel').forEach(function(panel) {
                panel.classList.add('hidden');
            });

            clickedBtn.classList.add('srv-active');
            clickedBtn.classList.remove('srv-inactive');
            clickedBtn.setAttribute('aria-selected', 'true');

